class I18nManager:
    _instance: Optional["I18nManager"] = None

    def __init__(self):
        self._settings = QSettings("galIMV", "galIMVmini")
        self._current_locale = self._settings.value("language", "ru_RU")
        if not any(code == self._current_locale for code, _ in LOCALES):
            self._current_locale = "ru_RU"

        self._translations: Dict[str, Any] = {}
        self._fallback_en: Dict[str, Any] = {}
        self._listeners: List[Callable[[], None]] = []

        self._load_all_translations()

    @classmethod
    def get_instance(cls) -> "I18nManager":
        if cls._instance is None:
            cls._instance = I18nManager()
        return cls._instance

    def _get_locales_dir(self) -> str:
        # Check bundled directory for PyInstaller or relative folder
        bundle_dir = getattr(sys, "_MEIPASS", "")
        if bundle_dir:
            p = os.path.join(bundle_dir, "locales")
            if os.path.exists(p):
                return p

        # Check adjacent to main.py
        p1 = os.path.join(os.path.dirname(__file__), "..", "locales")
        if os.path.exists(p1):
            return os.path.abspath(p1)

        p2 = os.path.join(os.getcwd(), "locales")
        if os.path.exists(p2):
            return os.path.abspath(p2)

        return os.path.abspath(p1)

    def _load_all_translations(self):
        locales_dir = self._get_locales_dir()
        
        # Load en_US as fallback
        en_path = os.path.join(locales_dir, "en_US.json")
        if os.path.exists(en_path):
            try:
                with open(en_path, "r", encoding="utf-8") as f:
                    self._fallback_en = json.load(f)
            except Exception:
                self._fallback_en = {}

        # Load active locale
        curr_path = os.path.join(locales_dir, f"{self._current_locale}.json")
        if os.path.exists(curr_path):
            try:
                with open(curr_path, "r", encoding="utf-8") as f:
                    self._translations = json.load(f)
            except Exception:
                self._translations = self._fallback_en
        else:
            self._translations = self._fallback_en

    def set_locale(self, locale_code: str):
        if locale_code == self._current_locale:
            return
        if not any(code == locale_code for code, _ in LOCALES):
            return

        self._current_locale = locale_code
        self._settings.setValue("language", locale_code)
        self._settings.sync()
        self._load_all_translations()
        self._notify()

    def get_locale(self) -> str:
        return self._current_locale

    def add_listener(self, callback: Callable[[], None]):
        if callback not in self._listeners:
            self._listeners.append(callback)

    def remove_listener(self, callback: Callable[[], None]):
        if callback in self._listeners:
            self._listeners.remove(callback)

    def _notify(self):
        for cb in self._listeners:
            try:
                cb()
            except Exception:
                pass

    def tr(self, key: str, default: str = "") -> str:
        """
        Translates key using active locale.
        Key format: 'section.subkey' (e.g. 'toolbar.open', 'inspector.aspect_ratio').
        """
        # 1. Check mini-specific fallbacks
        curr_mini = MINI_FALLBACKS.get(self._current_locale, {})
        if key in curr_mini:
            return curr_mini[key]

        # 2. Check loaded locale JSON
        val = self._lookup(self._translations, key)
        if val is not None and isinstance(val, str) and val.strip():
            return val

        # 3. Check English fallback
        val_en = self._lookup(self._fallback_en, key)
        if val_en is not None and isinstance(val_en, str) and val_en.strip():
            return val_en

        # 4. Check en_US mini fallback
        en_mini = MINI_FALLBACKS.get("en_US", {})
        if key in en_mini:
            return en_mini[key]

        return default or key

    def _lookup(self, data: Dict[str, Any], key: str) -> Optional[str]:
        parts = key.split(".")
        curr = data
        for p in parts:
            if isinstance(curr, dict) and p in curr:
                curr = curr[p]
            else:
                return None
        return curr if isinstance(curr, str) else None
